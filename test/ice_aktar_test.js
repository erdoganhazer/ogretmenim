const eski = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
eski.alistirmalar = fs.existsSync(process.argv[3]) ? fs.readFileSync(process.argv[3], "utf8").trim().split("\n").filter(Boolean).map(JSON.parse) : [];
