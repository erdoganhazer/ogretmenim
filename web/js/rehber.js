/* ---------- Seçici ---------- */
const rehberDeste = (() => { try { return JSON.parse(localStorage.getItem("ogretmenim-rehber") || "{}"); } catch (_) { return {}; } })();

function rehberSec(durumAdi) {
  const liste = REHBER[durumAdi];
  if (!liste) return "";
  let d = rehberDeste[durumAdi];
  if (!d || !Array.isArray(d.sira) || d.sira.length !== liste.length || d.i >= d.sira.length) {
    const son = d && d.sira ? d.sira[d.sira.length - 1] : -1;
    const sira = liste.map((_, i) => i);
    for (let i = sira.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [sira[i], sira[j]] = [sira[j], sira[i]]; }
    if (sira[0] === son && sira.length > 1) [sira[0], sira[1]] = [sira[1], sira[0]];
    d = rehberDeste[durumAdi] = { sira, i: 0 };
  }
  const cumle = liste[d.sira[d.i++]];
  try { localStorage.setItem("ogretmenim-rehber", JSON.stringify(rehberDeste)); } catch (_) {}
  return cumle;
}

